def create_config(*, project_root, data_root, output_root, vmamba_root,
                  vmamba_checkpoint, folds=(1, 2, 3, 4, 5), run_id='public_reproduction',
                  num_workers=4, fold_root=None):
    if not folds or any(f not in range(1, 6) for f in folds) or len(set(folds)) != len(folds):
        raise ValueError('Select distinct folds from 1 through 5.')
    project = Path(project_root).expanduser().resolve()
    data = Path(data_root).expanduser().resolve()
    output = Path(output_root).expanduser().resolve()
    if output == project or output == data or output in data.parents or data in output.parents:
        raise ValueError('Training output must be separate from source data.')
    cfg = copy.deepcopy(DEFAULTS)
    cfg.update(project_name='DCTG-VMamba', protocol_id='revision_primary_official_grouped_5fold_v1',
               run_id=run_id, baseline_project_root=str(data), _project_root=str(project),
               _only_models=['dctg_vmamba'], _only_folds=list(folds), _force=False,
               results={'root': str(output)}, run={'models': ['dctg_vmamba']})
    cfg['hardware']['num_workers'] = num_workers
    cfg['cache'] = {'max_gb': 8, 'warm_before_training': False}
    cfg['revision'] = {'require_checkpoint': True, 'export_validation': True,
                       'export_details': False, 'checkpoint_policy': 'fold_end',
                       'resume_training': False, 'persistent_epoch_workers': True,
                       'skip_test': False, 'disable_reporting': True, 'mask_overlay_limit': 0,
                       'fine_only_supervision': False, 'checkpoint_origin': 'public_reproduction'}
    locked = Path(fold_root).expanduser().resolve() if fold_root else project/'data/locked_folds_official'
    for name, dataset in cfg['datasets'].items():
        dataset['locked_fold_root'] = str(locked/name)
    vmamba = Path(vmamba_root).expanduser().resolve()
    cfg['models'][0]['backbone'].update(repo_path=str(vmamba/'classification/models'),
                                       extra_sys_paths=[str(vmamba/'classification')],
                                       checkpoint_path=str(Path(vmamba_checkpoint).expanduser().resolve()))
    return cfg
